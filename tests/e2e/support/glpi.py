"""GLPI verification helpers that keep ticket contents and OAuth tokens private."""

from __future__ import annotations

import html
import re
from collections.abc import Mapping
from dataclasses import dataclass, field
from typing import Protocol
from uuid import UUID

import httpx
from pydantic import SecretStr

from glpi_ticketing_glpi import (
    GLPI_API_VERSION,
    GlpiClient,
    TicketId,
    TicketStatus,
)

GLPI_HTTP_TIMEOUT_SECONDS = 10.0
_TICKET_PATH = f"/api.php/v{GLPI_API_VERSION}/Assistance/Ticket"
_TRANSCRIPTION_PARAGRAPH = re.compile(r"\A\s*<p>(.*?)</p>", flags=re.DOTALL)


class _GlpiCredentials(Protocol):
    username: str
    password: str
    client_id: str
    client_secret: str


class _GlpiEnvironment(Protocol):
    base_url: str

    @property
    def credentials(self) -> _GlpiCredentials:
        """Return ephemeral integration credentials."""


@dataclass(frozen=True, slots=True, kw_only=True)
class GlpiTicketRecord:
    """One correlated ticket whose dynamic contents stay out of representations."""

    ticket_id: int
    external_id: str
    status: TicketStatus
    title: str
    content: str = field(repr=False)

    def contains_non_empty_transcription(self) -> bool:
        """Return whether GLPI retained a non-empty first paragraph."""
        match = _TRANSCRIPTION_PARAGRAPH.match(self.content)
        if match is None:
            return False
        transcription = re.sub(r"<br>\s*", "\n", match.group(1))
        return bool(html.unescape(transcription).strip())

    def references_audio_url(self, audio_url: str) -> bool:
        """Require the exact escaped link paragraph generated by the client."""
        escaped_url = html.escape(audio_url, quote=True)
        paragraph = f'<p>Audio : <a href="{escaped_url}">{escaped_url}</a></p>'
        return paragraph in self.content


def load_correlated_glpi_ticket(
    environment: _GlpiEnvironment,
    audio_uuid: UUID,
    ticket_id: int,
) -> GlpiTicketRecord:
    """Load exactly one ticket by external ID and confirm its direct ID contract."""
    _require_audio_uuid(audio_uuid)
    _require_ticket_id(ticket_id)
    with httpx.Client() as http_client:
        client = _build_client(environment, http_client)
        token = client.authenticate()
        tickets = _search_tickets(
            environment,
            http_client,
            token_type=token.token_type,
            access_token=token.access_token,
            audio_uuid=audio_uuid,
        )
        if len(tickets) != 1:
            raise AssertionError("GLPI did not return exactly one correlated ticket")
        snapshot = client.get_ticket(TicketId(ticket_id))

    ticket = tickets[0]
    returned_id = _positive_integer(ticket.get("id"), "GLPI ticket id")
    external_id = _non_empty_string(ticket.get("external_id"), "external_id")
    title = _non_empty_string(ticket.get("name"), "ticket title")
    content = _non_empty_string(ticket.get("content"), "ticket content")
    if returned_id != ticket_id or snapshot.ticket_id != ticket_id:
        raise AssertionError("GLPI ticket identifiers are inconsistent")
    if external_id != str(audio_uuid) or snapshot.external_id != str(audio_uuid):
        raise AssertionError("GLPI external ID is inconsistent")
    return GlpiTicketRecord(
        ticket_id=returned_id,
        external_id=external_id,
        status=snapshot.status,
        title=title,
        content=content,
    )


def count_glpi_tickets(
    environment: _GlpiEnvironment,
    audio_uuid: UUID,
) -> int:
    """Count the bounded exact-external-ID result without exposing its contents."""
    _require_audio_uuid(audio_uuid)
    with httpx.Client() as http_client:
        client = _build_client(environment, http_client)
        token = client.authenticate()
        tickets = _search_tickets(
            environment,
            http_client,
            token_type=token.token_type,
            access_token=token.access_token,
            audio_uuid=audio_uuid,
        )
    return len(tickets)


def _build_client(
    environment: _GlpiEnvironment,
    http_client: httpx.Client,
) -> GlpiClient:
    credentials = environment.credentials
    return GlpiClient(
        base_url=environment.base_url,
        username=credentials.username,
        password=SecretStr(credentials.password),
        client_id=credentials.client_id,
        client_secret=SecretStr(credentials.client_secret),
        http_client=http_client,
        timeout=GLPI_HTTP_TIMEOUT_SECONDS,
    )


def _search_tickets(
    environment: _GlpiEnvironment,
    http_client: httpx.Client,
    *,
    token_type: str,
    access_token: SecretStr,
    audio_uuid: UUID,
) -> tuple[Mapping[str, object], ...]:
    response = http_client.get(
        f"{environment.base_url}{_TICKET_PATH}",
        headers={
            "Accept": "application/json",
            "Authorization": (f"{token_type} {access_token.get_secret_value()}"),
        },
        params={"filter": f"external_id=={audio_uuid}", "limit": "2"},
        timeout=GLPI_HTTP_TIMEOUT_SECONDS,
        follow_redirects=False,
    )
    if response.status_code not in {httpx.codes.OK, httpx.codes.PARTIAL_CONTENT}:
        raise AssertionError(
            "GLPI exact external-ID lookup returned an unexpected HTTP status"
        )
    try:
        payload = response.json()
    except ValueError:
        raise AssertionError(
            "GLPI exact external-ID lookup returned invalid JSON"
        ) from None
    if not isinstance(payload, list):
        raise AssertionError("GLPI exact external-ID lookup returned no collection")
    if any(not isinstance(ticket, Mapping) for ticket in payload):
        raise AssertionError("GLPI exact external-ID lookup returned an invalid item")
    return tuple(payload)


def _require_audio_uuid(value: object) -> None:
    if not isinstance(value, UUID):
        raise TypeError("audio_uuid must be a UUID")


def _require_ticket_id(value: object) -> None:
    if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
        raise ValueError("ticket_id must be a positive integer")


def _positive_integer(value: object, field_name: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
        raise AssertionError(f"{field_name} is invalid")
    return value


def _non_empty_string(value: object, field_name: str) -> str:
    if not isinstance(value, str) or not value:
        raise AssertionError(f"{field_name} is invalid")
    return value


